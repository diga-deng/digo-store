// Use the same cover transform as the photo, so a marker stays on its real object.
function scenePhotoPoint(point, imageWidth, imageHeight, width, height, position) {
  const scale=Math.max(width/imageWidth,height/imageHeight);
  return {x:point.x*imageWidth*scale+(width-imageWidth*scale)*position[0],y:point.y*imageHeight*scale+(height-imageHeight*scale)*position[1]};
}
let sceneHotspotObserver;
function mountSceneHotspots() {
  sceneHotspotObserver?.disconnect();
  const section=document.querySelector('.life-scene[data-real-room]');
  if(!section)return;
  const scene=[...baseScenes,...archivedScenes].find(s=>s.id===section.dataset.scene),photo=section.querySelector('.life-scene-photo');
  const update=()=>{
    const width=section.clientWidth,height=section.clientHeight,rect=section.getBoundingClientRect();
    const rail=section.querySelector('.life-rail')?.getBoundingClientRect();
    scene.hotspots.forEach((h,i)=>{
      const button=section.querySelector(`[data-hotspot-index="${i}"]`),line=section.querySelector(`[data-hotspot-line="${i}"]`);
      const anchor=scenePhotoPoint(h,scene.width,scene.height,width,height,scene.position);
      const label=scenePhotoPoint({x:h.labelX??h.x,y:h.labelY??h.y},scene.width,scene.height,width,height,scene.position);
      const visible=anchor.x>=0&&anchor.x<=width&&anchor.y>=0&&anchor.y<=height;
      button.hidden=!visible;line.style.display=visible?'':'none';if(!visible)return;
      label.x=Math.max(24,Math.min(width-24,label.x));label.y=Math.max(60,Math.min(height-110,label.y));
      if(rail&&label.y>rail.top-rect.top-24&&label.y<rail.bottom-rect.top+24&&label.x<rail.right-rect.left+24)label.x=rail.right-rect.left+30;
      button.style.left=label.x+'px';button.style.top=label.y+'px';
      line.setAttribute('x1',anchor.x);line.setAttribute('y1',anchor.y);line.setAttribute('x2',label.x);line.setAttribute('y2',label.y);
    });
  };
  photo.addEventListener('load',update,{once:true});
  if(typeof ResizeObserver!=='undefined'){sceneHotspotObserver=new ResizeObserver(update);sceneHotspotObserver.observe(section);}
  update();
}
